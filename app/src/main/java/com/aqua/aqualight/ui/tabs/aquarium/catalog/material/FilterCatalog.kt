object FilterCatalog {

    val definitions: List<AquariumMaterialDefinition> =
        filterCatalogResources.map { resource ->
            AquariumMaterialDefinition(
                id = resource.id,
                brandRes = resource.brandRes,
                nameRes = resource.nameRes,
                categoryKey = MaterialCategoryKey.FILTER,
                categoryTitleRes = R.string.catalog_material_category_filter_title,
                keywordRes = (
                    listOf(
                        R.string.catalog_keyword_filter,
                        R.string.catalog_filter_keyword_aquarium_filter
                    ) +
                        resource.hardwareType.keywordRes +
                        resource.extraKeywordRes
                    ).distinct()
            )
        }

    init {
        check(definitions.size == FILTER_PRODUCT_COUNT)
        check(definitions.map(AquariumMaterialDefinition::id).distinct().size == definitions.size)
        check(definitions.map(AquariumMaterialDefinition::nameRes).distinct().size == definitions.size)
        check(definitions.map(AquariumMaterialDefinition::brandRes).distinct().size == FILTER_BRAND_COUNT)
        check(definitions.all { definition -> definition.id.startsWith("filter_") })
    }
}


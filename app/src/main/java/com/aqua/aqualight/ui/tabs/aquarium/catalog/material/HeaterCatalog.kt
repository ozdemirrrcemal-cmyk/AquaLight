object HeaterCatalog {

    val definitions: List<AquariumMaterialDefinition> =
        heaterCatalogResources.map { resource ->
            AquariumMaterialDefinition(
                id = resource.id,
                brandRes = resource.brandRes,
                nameRes = resource.nameRes,
                categoryKey = MaterialCategoryKey.HEATER,
                categoryTitleRes = R.string.catalog_material_category_heater_title,
                keywordRes = (
                    listOf(
                        R.string.catalog_heater_keyword_heater,
                        R.string.catalog_heater_keyword_aquarium_heater,
                        R.string.catalog_keyword_temperature
                    ) +
                        resource.hardwareType.keywordRes +
                        resource.extraKeywordRes
                    ).distinct()
            )
        }

    init {
        check(definitions.size == HEATER_PRODUCT_COUNT)
        check(definitions.map(AquariumMaterialDefinition::id).distinct().size == definitions.size)
        check(definitions.map(AquariumMaterialDefinition::nameRes).distinct().size == definitions.size)
        check(definitions.map(AquariumMaterialDefinition::brandRes).distinct().size == HEATER_BRAND_COUNT)
        check(definitions.all { definition -> definition.id.startsWith("heater_") })
    }
}

private fun heaterResource(
    id: String,
    brandRes: Int,
    nameRes: Int,
    hardwareType: HeaterHardwareType,
    vararg extraKeywordRes: Int
): HeaterCatalogResource = HeaterCatalogResource(
    id = id,
    brandRes = brandRes,
    nameRes = nameRes,
    hardwareType = hardwareType,
    extraKeywordRes = extraKeywordRes.toList()
)
